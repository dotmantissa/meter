import { chromium } from '../web/node_modules/playwright/index.mjs';
import { mkdirSync, writeFileSync } from 'node:fs';
const browser = await chromium.launch({ executablePath: '/home/dotmantissa/.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
const page = await context.newPage(); const errors = [], failures = [];
page.on('pageerror', e => errors.push(e.message));
page.on('response', r => { if (r.status() >= 400 && !r.url().includes('/api/')) failures.push({ status: r.status(), url: new URL(r.url()).origin + new URL(r.url()).pathname }); });
await page.goto(process.env.METER_PREVIEW_URL || 'http://127.0.0.1:8787/', { waitUntil: 'domcontentloaded', timeout: 120000 });
await page.getByRole('heading', { name: /Your bill/, level: 1 }).waitFor();
mkdirSync('.contract-build', { recursive: true });
await page.screenshot({ path: '.contract-build/desktop.png', fullPage: true });
console.log({title:await page.title(),desktopOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),pageErrors:errors,failures});
await page.getByRole('button',{name:'Use dark mode'}).click();
await page.screenshot({path:'.contract-build/dark.png',fullPage:true});
console.log({darkTheme:await page.locator('html').getAttribute('data-theme')});
await page.getByRole('button',{name:'Use light mode'}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'.contract-build/mobile.png',fullPage:true});
console.log({mobileOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)});
await page.getByRole('button',{name:'Open navigation'}).click();
console.log({mobileNavVisible:await page.getByRole('navigation').isVisible()});
await page.getByRole('button',{name:'Close navigation'}).click();
await page.getByRole('button',{name:'Email sign in'}).first().click();
await page.waitForTimeout(1500);
console.log({emailModalVisible:await page.getByRole('textbox').count(),walletText:await page.getByText('Connect wallet',{exact:false}).count(),pageErrors:errors});
writeFileSync('.contract-build/browser-result.json',JSON.stringify({errors,failures},null,2));
await browser.close();
